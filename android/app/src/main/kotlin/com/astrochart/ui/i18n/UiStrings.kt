    fun ageValue(years: Int): String = when (lang) {
        Language.TA -> "$years வயது"
        Language.ZH -> "${years}岁"
        Language.HI -> "$years वर्ष"
        Language.TE -> "$years సంవత్సరాలు"
        Language.KN -> "$years ವರ್ಷ"
        Language.ML -> "$years വയസ്സ്"
        Language.MR -> "$years वर्षे"
        else -> "$years yrs"
    }

    fun houseLabel(house: Int): String = when (lang) {
        Language.TA -> "$house ஆம் வீடு"
        Language.ZH -> "第${house}宫"
        Language.HI -> "भाव $house"
        Language.TE -> "$house వ భావం"
        Language.KN -> "$house ನೇ ಭಾವ"
        Language.ML -> "$house-ാം ഭാവം"
        Language.MR -> "$house वे स्थान"
        else -> "House $house"
    }

    fun bodyCount(count: Int): String = when (lang) {
        Language.TA -> "$count கிரகம்"
        Language.ZH -> "${count}颗"
        Language.HI -> "$count ग्रह"
        Language.TE -> "$count గ్రహాలు"
        Language.KN -> "$count ಗ್ರಹಗಳು"
        Language.ML -> "$count ഗ്രഹങ്ങൾ"
        Language.MR -> "$count ग्रह"
        else -> if (count == 1) "1 body" else "$count bodies"
    }

    fun deleteMessage(name: String): String = when (lang) {
        Language.TA -> "\"$name\" நிரந்தரமாக நீக்கப்படும்."
        Language.ZH -> "将永久删除“$name”。"
        Language.HI -> "\"$name\" स्थायी रूप से हटा दिया जाएगा।"
        Language.TE -> "\"$name\" శాశ్వతంగా తొలగించబడుతుంది."
        Language.KN -> "\"$name\" ಶಾಶ್ವತವಾಗಿ ಅಳಿಸಲಾಗುತ್ತದೆ."
        Language.ML -> "\"$name\" ശാശ്വതമായി ഇല്ലാതാക്കപ്പെടും."
        Language.MR -> "\"$name\" कायमचे हटवले जाईल."
        else -> "\"$name\" will be permanently removed."
    }


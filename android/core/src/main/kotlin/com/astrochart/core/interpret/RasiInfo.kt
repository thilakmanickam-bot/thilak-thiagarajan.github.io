package com.astrochart.core.interpret

import com.astrochart.core.i18n.Language

/**
 * A short localized string across the supported languages. [en]/[ta]/[zh] are
 * always given; the Indic forms default to the English romanization for values
 * not yet translated.
 */
data class L3(
    val en: String,
    val ta: String,
    val zh: String,
    val hi: String = en,
    val te: String = en,
    val kn: String = en,
    val ml: String = en,
    val mr: String = en
) {
    fun get(lang: Language): String = when (lang) {
        Language.TA -> ta
        Language.ZH -> zh
        Language.HI -> hi
        Language.TE -> te
        Language.KN -> kn
        Language.ML -> ml
        Language.MR -> mr
        else -> en
    }
}


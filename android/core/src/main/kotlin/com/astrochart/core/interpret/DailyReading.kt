/** A colour with a localized name and an ARGB value for a swatch. */
data class DailyColor(
    val nameEn: String,
    val nameTa: String,
    val nameZh: String,
    val nameHi: String,
    val nameTe: String,
    val nameKn: String,
    val nameMl: String,
    val nameMr: String,
    val hex: Long
) {
    fun name(lang: Language): String = when (lang) {
        Language.TA -> nameTa
        Language.ZH -> nameZh
        Language.HI -> nameHi
        Language.TE -> nameTe
        Language.KN -> nameKn
        Language.ML -> nameMl
        Language.MR -> nameMr
        else -> nameEn
    }
}

